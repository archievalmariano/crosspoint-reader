"""Vendor the issue server's /current.json router vectors for the firmware tests.

The public DOGEAR repository generates hosting/dogear-site/test/vectors.json from
its reference router (tools/route_vectors.py). This copies every GET /current.json
case into RouterVectors.inc, with the source file's SHA-256, so the firmware's
"nothing published" classification is tested against exactly what the server sends.

    python3 test/dogear/fixtures/extract_router_vectors.py <dogear checkout>
"""
import hashlib
import json
import sys
from pathlib import Path

SOURCE = "hosting/dogear-site/test/vectors.json"
OUT = Path(__file__).resolve().parent / "RouterVectors.inc"


def cxx(text: str) -> str:
    out = []
    for ch in text:
        if ch == "\\" or ch == '"':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20 or ord(ch) > 0x7E:
            out.append("".join(f"\\x{b:02x}\"\"" for b in ch.encode("utf-8")))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    data = (Path(sys.argv[1]) / SOURCE).read_bytes()
    cases = [c for c in json.loads(data)["cases"] if c["method"] == "GET" and c["path"] == "/current.json"]
    lines = [
        "// GENERATED by test/dogear/fixtures/extract_router_vectors.py from the public",
        f"// DOGEAR repository's {SOURCE}; do not edit by hand.",
        f"// sourceSha256: {hashlib.sha256(data).hexdigest()}",
        f"// GET /current.json cases: {len(cases)}",
    ]
    for c in cases:
        e = c["expect"]
        headers = "".join(f"{k}: {v}\r\n" for k, v in sorted(e["headers"].items()))
        lines.append(f"{{{cxx(c['store'])}, {e['status']}, {cxx(headers)}, {cxx(e['body'])}}},")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.name}: {len(cases)} cases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
