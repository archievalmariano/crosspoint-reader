#!/usr/bin/env python3
"""Embed one DOGEAR issue JSON as the firmware's compiled-in fallback issue.

The device shows this issue only when it has neither a network issue nor an SD
cache (marked OFFLINE). It is synthetic: one week of the public DOGEAR staging
fixture, never editorial content. From a checkout of the public dogear repo:

    python3 -m dogear.cli --dataset fixtures/staging-year.json issue \
      --week 2026-11-23 --out /tmp/builtin --issues /tmp/builtin --preview \
      --now 2026-11-23T06:00:00+08:00 --base-url https://dogear-staging.pages.dev --quiet
    python3 embed_issue.py /tmp/builtin/dogear-2026-11-23.json

Output: ../DogearBuiltinIssue.generated.h. The bytes are copied verbatim into a
raw string literal; the firmware parser validates them at runtime.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "DogearBuiltinIssue.generated.h"))
DELIM = "DOGEARJSON"


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: embed_issue.py ISSUE_JSON")
    with open(sys.argv[1], encoding="utf-8") as f:
        text = f.read()
    issue = json.loads(text)  # refuse to embed a file that does not parse
    if (")" + DELIM + '"') in text:
        raise SystemExit("issue collides with the raw-string delimiter; change DELIM")
    lines = [
        "// GENERATED by src/activities/dogear/tools/embed_issue.py -- do not edit by hand.",
        f"// Source: {os.path.basename(sys.argv[1])} from the public staging fixture (synthetic; verbatim; validated at runtime).",
        "#pragma once",
        "",
        f'static constexpr char kDogearBuiltinIssueJson[] = R"{DELIM}({text}){DELIM}";',
        "",
    ]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT} ({issue['issueId']}, {len(text.encode('utf-8'))} bytes)")


if __name__ == "__main__":
    main()
